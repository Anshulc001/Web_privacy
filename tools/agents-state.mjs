import { readFile, writeFile, readdir } from "node:fs/promises";
import { resolve } from "node:path";

/**
 * Keeps the "Current state" block in AGENTS.md truthful.
 *
 * The block is generated from the repository itself, so a new session can trust
 * the numbers without re-deriving them, and `tests/agents-doc.test.mjs` fails
 * when the block no longer matches the files. Only values that change when the
 * code or data changes are included; nothing time-based, so running this twice
 * produces identical output.
 *
 * Usage:
 *   node tools/agents-state.mjs            print the block
 *   node tools/agents-state.mjs --write    replace the block in AGENTS.md
 *   node tools/agents-state.mjs --check    exit 1 when AGENTS.md is stale
 */

const ROOT = resolve(import.meta.dirname, "..");
export const AGENTS_FILE = resolve(ROOT, "AGENTS.md");
export const BEGIN_MARKER = "<!-- BEGIN:AGENTS-STATE -->";
export const END_MARKER = "<!-- END:AGENTS-STATE -->";

async function readJson(relativePath) {
  return JSON.parse(await readFile(resolve(ROOT, relativePath), "utf8"));
}

function isoDay(buildDate) {
  return typeof buildDate === "string" && /^\d{4}-\d{2}-\d{2}/.test(buildDate) ? buildDate.slice(0, 10) : "unknown";
}

function count(value) {
  const number = Number(value);
  return Number.isFinite(number) ? number.toLocaleString("en-US") : "unknown";
}

/** The facts a session would otherwise have to recompute by hand. */
export async function collectState() {
  const manifest = await readJson("manifest.json");
  const blocking = await readJson("data/ad-tracker-data.json");
  const rules = await readJson("data/ad-tracker-rules.json");
  const cosmetic = await readJson("data/cosmetic-rules.json");
  const breach = await readJson("data/breach-data.json");
  const threat = await readJson("data/threat-list.json");
  const settings = await import("../lib/storage-settings.mjs");
  const tests = (await readdir(resolve(ROOT, "tests"))).filter((name) => name.endsWith(".test.mjs"));

  const hostRules = blocking?.stats?.publishedHostRules;
  const pathRules = blocking?.stats?.publishedPathRules;
  const blockingDay = isoDay(blocking?.buildDate);

  return {
    version: String(manifest.version ?? "unknown"),
    minimumChrome: String(manifest.minimum_chrome_version ?? "unset"),
    permissions: Array.isArray(manifest.permissions) ? manifest.permissions.join(", ") : "unknown",
    rulesTotal: rules.length,
    hostRules,
    pathRules,
    blockingBuildDate: blockingDay,
    cosmeticDomains: cosmetic?.stats?.domains,
    cosmeticSelectors: cosmetic?.stats?.publishedSelectors,
    cosmeticBuildDate: isoDay(cosmetic?.buildDate),
    breachBuildDate: isoDay(breach?.buildDate),
    threatBuildDate: isoDay(threat?.buildDate),
    retentionHours: settings.DEFAULT_SETTINGS.historyRetentionHours,
    testFiles: tests.length
  };
}

/** The generated block, markers included. Deterministic for a given repository state. */
export async function buildStateBlock() {
  const state = await collectState();
  const retentionDays = Math.round(state.retentionHours / 24);
  const lines = [
    BEGIN_MARKER,
    "<!-- Generated by `npm run agents:state` from the repository. Do not edit by hand. -->",
    `- Extension version: \`${state.version}\` (minimum Chrome ${state.minimumChrome})`,
    `- Static DNR ruleset: ${count(state.rulesTotal)} rules (${count(state.hostRules)} host + ${count(state.pathRules)} path), data built ${state.blockingBuildDate}`,
    `- Cosmetic data: ${count(state.cosmeticDomains)} domains, ${count(state.cosmeticSelectors)} selectors, built ${state.cosmeticBuildDate}`,
    `- Breach data built: ${state.breachBuildDate}`,
    `- Phishing list built: ${state.threatBuildDate}`,
    `- Default visit-record retention: ${state.retentionHours} hours (${retentionDays} days)`,
    `- Manifest permissions: ${state.permissions}`,
    `- Test files: ${state.testFiles}`,
    END_MARKER
  ];
  return lines.join("\n");
}

/** Replaces the marked block, refusing to guess when the markers are missing. */
export function replaceStateBlock(markdown, block) {
  const start = markdown.indexOf(BEGIN_MARKER);
  const end = markdown.indexOf(END_MARKER);
  if (start === -1 || end === -1 || end < start) {
    throw new Error("AGENTS.md is missing the Current state markers; restore them before running this script.");
  }
  return `${markdown.slice(0, start)}${block}${markdown.slice(end + END_MARKER.length)}`;
}

async function main() {
  const mode = process.argv[2] ?? "--print";
  const block = await buildStateBlock();
  const markdown = await readFile(AGENTS_FILE, "utf8");

  if (mode === "--print") {
    console.log(block);
    return;
  }
  if (mode === "--write") {
    const next = replaceStateBlock(markdown, block);
    if (next === markdown) {
      console.log("AGENTS.md state block is already current.");
      return;
    }
    await writeFile(AGENTS_FILE, next);
    console.log("Updated the AGENTS.md state block.");
    return;
  }
  if (mode === "--check") {
    if (markdown.includes(block)) {
      console.log("AGENTS.md state block is current.");
      return;
    }
    console.error("AGENTS.md state block is stale. Run `npm run agents:state` and commit the result.");
    process.exitCode = 1;
    return;
  }
  throw new Error(`Unknown mode: ${mode}. Use --print, --write or --check.`);
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  await main();
}
